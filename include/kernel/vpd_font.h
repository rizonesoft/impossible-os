/* ---- Rendering functions (all static inline) ----------------------------- */

/* Render one character at pixel position (x,y) on a raw framebuffer. */
static inline void vpd_putchar(uint32_t *fb, uint32_t pitch_px,
                                uint32_t x, uint32_t y,
                                char c, uint32_t color)
{
    const uint8_t *glyph;
    uint32_t row, col;

    if (c < VPD_FIRST || c > VPD_LAST)
        c = '?';

    glyph = vpd_font_data[c - VPD_FIRST];

    for (row = 0; row < VPD_GLYPH_H; row++) {
        uint8_t bits = glyph[row];
        for (col = 0; col < VPD_GLYPH_W; col++) {
            if (bits & (0x80 >> col))
                fb[(y + row) * pitch_px + (x + col)] = color;
        }
    }
}

/* Render a null-terminated string. Advances x by VPD_CELL_W per char. */
static inline void vpd_puts(uint32_t *fb, uint32_t pitch_px,
                              uint32_t x, uint32_t y,
                              const char *s, uint32_t color)
{
    while (*s) {
        vpd_putchar(fb, pitch_px, x, y, *s, color);
        x += VPD_CELL_W;
        s++;
    }
}

/* Render an unsigned 32-bit integer as decimal text. */
static inline void vpd_putu32(uint32_t *fb, uint32_t pitch_px,
                                uint32_t x, uint32_t y,
                                uint32_t val, uint32_t color)
{
    char buf[12];
    int i = 0, j;

    if (val == 0) {
        vpd_putchar(fb, pitch_px, x, y, '0', color);
        return;
    }

    while (val > 0 && i < 11) {
        buf[i++] = (char)('0' + val % 10);
        val /= 10;
    }

    /* Reverse and render */
    for (j = i - 1; j >= 0; j--) {
        vpd_putchar(fb, pitch_px, x, y, buf[j], color);
        x += VPD_CELL_W;
    }
}

/* Render a 16-bit value as 4-digit hex (e.g., "B001"). */
static inline void vpd_puthex16(uint32_t *fb, uint32_t pitch_px,
                                  uint32_t x, uint32_t y,
                                  uint16_t val, uint32_t color)
{
    static const char hex[] = "0123456789ABCDEF";
    vpd_putchar(fb, pitch_px, x,                  y, hex[(val >> 12) & 0xF], color);
    vpd_putchar(fb, pitch_px, x + VPD_CELL_W,     y, hex[(val >>  8) & 0xF], color);
    vpd_putchar(fb, pitch_px, x + VPD_CELL_W * 2, y, hex[(val >>  4) & 0xF], color);
    vpd_putchar(fb, pitch_px, x + VPD_CELL_W * 3, y, hex[ val        & 0xF], color);
}

/* Render a byte as 2-digit hex (e.g., "FF"). */
static inline void vpd_puthex8(uint32_t *fb, uint32_t pitch_px,
                                 uint32_t x, uint32_t y,
                                 uint8_t val, uint32_t color)
{
    static const char hex[] = "0123456789ABCDEF";
    vpd_putchar(fb, pitch_px, x,              y, hex[(val >> 4) & 0xF], color);
    vpd_putchar(fb, pitch_px, x + VPD_CELL_W, y, hex[ val       & 0xF], color);
}
