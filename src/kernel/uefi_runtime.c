boot_result_t uefi_time_init(void)
{
    struct efi_time t;
    struct efi_time_capabilities caps;

    efi_status_t status = uefi_get_time(&t, &caps);
    if (status != UEFI_SUCCESS) {
        klog(LOG_WARN, "UEFI", "GetTime failed -- wall clock not seeded");
        return BOOT_DEGRADED;
    }

    /* Format: "YYYY-MM-DD HH:MM:SS" -- manual zero-padding (no %02u in klog) */
    char ts[20];
    uint16_t y = t.year;
    ts[0]  = '0' + (char)(y / 1000);
    ts[1]  = '0' + (char)((y / 100) % 10);
    ts[2]  = '0' + (char)((y / 10) % 10);
    ts[3]  = '0' + (char)(y % 10);
    ts[4]  = '-';
    ts[5]  = '0' + (char)(t.month / 10);
    ts[6]  = '0' + (char)(t.month % 10);
    ts[7]  = '-';
    ts[8]  = '0' + (char)(t.day / 10);
    ts[9]  = '0' + (char)(t.day % 10);
    ts[10] = ' ';
    ts[11] = '0' + (char)(t.hour / 10);
    ts[12] = '0' + (char)(t.hour % 10);
    ts[13] = ':';
    ts[14] = '0' + (char)(t.minute / 10);
    ts[15] = '0' + (char)(t.minute % 10);
    ts[16] = ':';
    ts[17] = '0' + (char)(t.second / 10);
    ts[18] = '0' + (char)(t.second % 10);
    ts[19] = '\0';

    klog(LOG_INFO, "UEFI", "RTC: %s", ts);

    /* Timezone info */
    if (t.timezone == (int16_t)EFI_UNSPECIFIED_TIMEZONE) {
        klog(LOG_INFO, "UEFI", "RTC: timezone unspecified (local time)");
    } else {
        int16_t tz = t.timezone;
        uint32_t abs_tz = (uint32_t)((tz >= 0) ? tz : -tz);
        klog(LOG_INFO, "UEFI", "RTC: UTC%s%u:%s%u",
             (tz >= 0) ? "+" : "-",
             abs_tz / 60,
             (abs_tz % 60 < 10) ? "0" : "",
             abs_tz % 60);
    }

    klog(LOG_INFO, "UEFI", "RTC: resolution=%u Hz, accuracy=%u ppm",
         caps.resolution, caps.accuracy);

    return BOOT_OK;
}

/* ============================================================================
 * Secure Boot State Detection
 *
 * Reads UEFI NVRAM variables to determine Secure Boot state.
 * ============================================================================ */

static int s_sb_enabled;      /* SecureBoot variable = 1 */
static int s_sb_state_valid;  /* 1 if SecureBoot var read returned authoritative
                                 value; 0 if read failed (state is unknown).
                                 The registry must NOT publish State when this
                                 is 0 -- consumers must see a separate
                                 StateValid=0 signal so the read-failure path
                                 is distinguishable from genuinely-disabled. */
static int s_sb_setup_mode;   /* SetupMode variable = 1 */
static int s_sb_deployed_mode;/* DeployedMode variable = 1 (UEFI 2.5+) */
static int s_sb_audit_mode;   /* AuditMode variable = 1 (UEFI 2.5+) */
static int s_sb_pk_present;   /* PK variable exists with data */
static int s_sb_kek_present;  /* KEK variable exists with data */

/* Helper: read a single-byte UEFI global variable. Returns the byte, or -1.
 *
 * SUCCESS alone is not enough -- a buggy or hostile firmware can return
 * SUCCESS with sz != 1, leaving `val` at the zero-init or filling only
 * part of the byte.  Require both SUCCESS AND sz == sizeof(val);
 * anything else is a read failure. */
static int read_global_byte(const uint16_t *name)
{
    struct boot_uefi_guid global = EFI_GLOBAL_VARIABLE_GUID;
    uint8_t val = 0;
    uint64_t sz = sizeof(val);
    uint32_t attrs = 0;

    efi_status_t status = uefi_get_variable(&global, name, &attrs, &sz, &val);
    if (status != UEFI_SUCCESS || sz != sizeof(val))
        return -1;
    return (int)val;
}

/* SHIM_LOCK_GUID -- Microsoft shim namespace for SBAT (Secure Boot
 * Advanced Targeting) revocation tracking and shim-internal control
 * variables. SbatLevel lives here, NOT under EFI_GLOBAL_VARIABLE_GUID
 * (the firmware reads/writes shim-namespaced variables to coordinate
 * cumulative SBAT revocation levels across kernel + bootloader +
 * shim). Source: shim project sbat.c (SBAT_VAR_NAME under
 * SHIM_LOCK_GUID). Without this GUID a shim-protected boot reports
 * SBAT as absent because the wrong namespace returns NOT_FOUND. */
#define SHIM_LOCK_GUID                                                  \
    { 0x605dab50u, 0xe046u, 0x4300u,                                    \
      { 0xabu, 0xb6u, 0x3du, 0xd8u, 0x10u, 0xddu, 0x8bu, 0x23u } }

/* Read a UEFI variable string into a fixed-size buffer under any
 * vendor GUID. Returns the FIRMWARE-REPORTED byte count
 * (truncation-detection signal -- a value greater than
 * `out_buf_bytes - 1` means the payload was truncated to fit
 * `out`), or 0 if the variable is absent / unreadable / empty /
 * oversized. `out` is always NUL-terminated within
 * `[0, out_buf_bytes)`, even on failure (out[0] = '\0'); the first
 * up-to-`out_buf_bytes - 1` bytes of the payload are copied.
 *
 * Caller publishes the return value as a size field (e.g. boot_info
 * v18 sbat_level_size) so attestation tooling can detect truncation
 * by comparing against `sizeof(boot_info.sbat_level) - 1`. Without
 * this convention an exact `out_buf_bytes - 1`-byte payload and a
 * much-larger truncated payload would both publish with the same
 * stored size, hiding a load-bearing trust signal.
 *
 * Two-stage read: probe size with NULL data, then read into a fixed
 * stack scratch (READ_VAR_STRING_SCRATCH) sized comfortably above
 * any realistic SbatLevel string, then copy a capped prefix into
 * `out`. Variables larger than the scratch buffer are treated as
 * absent (size beyond practical SBAT level expectations is a
 * firmware quirk or hostile input). */
#define READ_VAR_STRING_SCRATCH 1024u
static uint64_t read_var_string(const struct boot_uefi_guid *guid,
                                const uint16_t *name,
                                char *out, uint64_t out_buf_bytes)
{
    if (out_buf_bytes == 0) return 0;
    out[0] = '\0';

    uint64_t sz = 0;
    uint32_t attrs = 0;

    /* Probe size with NULL data; firmware returns BUFFER_TOO_SMALL with
     * the real size, OR SUCCESS with sz=0 if the variable is empty. */
    efi_status_t s = uefi_get_variable(guid, name, &attrs, &sz, (void *)0);
    if ((s != UEFI_BUFFER_TOO_SMALL && s != UEFI_SUCCESS) || sz == 0)
        return 0;

    if (sz > READ_VAR_STRING_SCRATCH) {
        /* Pathological / hostile size; treat as absent. SBAT levels
         * realistically stay under 256 bytes; a multi-KiB payload is
         * a firmware quirk we should not propagate into boot_info.
         * Caller treats size=0 as ABSENT. */
        return 0;
    }

    uint8_t scratch[READ_VAR_STRING_SCRATCH];
    uint64_t read_sz = sz;
    s = uefi_get_variable(guid, name, &attrs, &read_sz, scratch);
    if (s != UEFI_SUCCESS || read_sz == 0)
        return 0;
    if (read_sz > READ_VAR_STRING_SCRATCH)
        read_sz = READ_VAR_STRING_SCRATCH;

    uint64_t copy_sz = read_sz;
    if (copy_sz > out_buf_bytes - 1) copy_sz = out_buf_bytes - 1;
    uint64_t i;
    for (i = 0; i < copy_sz; i++)
        out[i] = (char)scratch[i];
    out[copy_sz] = '\0';
    /* Return the firmware-reported size, NOT copy_sz, so the caller
     * can publish a truncation-detectable signal. */
    return read_sz;
}

/* Probe the byte size of a variable under EFI_IMAGE_SECURITY_DATABASE_
 * GUID (dbx / db / dbt) without reading contents. Returns the firmware-
 * reported payload size, or 0 if absent / unreadable / empty. The size
 * alone is the v18 trust-landscape signal -- the per-entry parse for
 * Registry inventory lives in secureboot_keys_init() above. Cheap call:
 * one GetVariable with NULL data. */
static uint64_t imgsec_var_size(const uint16_t *name)
{
    struct boot_uefi_guid imgsec = EFI_IMAGE_SECURITY_DATABASE_GUID;
    uint64_t sz = 0;
    uint32_t attrs = 0;
    efi_status_t s = uefi_get_variable(&imgsec, name, &attrs, &sz, (void *)0);
    if (s == UEFI_BUFFER_TOO_SMALL && sz > 0) return sz;
    if (s == UEFI_SUCCESS && sz > 0) return sz;
    return 0;
}

/* Helper: check if a UEFI global variable exists with non-zero size.
 *
 * SUCCESS-with-sz=0 must NOT count as "exists" for PK/KEK enrollment
 * checks.  Empty PK/KEK variables are firmware artifacts, not enrolled
 * keys; reporting them as enrolled would mislead Secure Boot status
 * consumers.  Require sz > 0 on either SUCCESS or BUFFER_TOO_SMALL.
 */
static int global_var_exists(const uint16_t *name)
{
    struct boot_uefi_guid global = EFI_GLOBAL_VARIABLE_GUID;
    uint64_t sz = 0;
    uint32_t attrs = 0;

    /* Call with size=0 to get the actual size via BUFFER_TOO_SMALL */
    efi_status_t status = uefi_get_variable(
        &global, name, &attrs, &sz, (void *)0);

    /* BUFFER_TOO_SMALL is the canonical "exists with data" signal */
    if (status == UEFI_BUFFER_TOO_SMALL && sz > 0)
        return 1;
    /* SUCCESS with sz > 0 also counts (firmware sized the buffer for us) */
    if (status == UEFI_SUCCESS && sz > 0)
        return 1;
    return 0;
}

boot_result_t uefi_secureboot_init(void)
{
    s_sb_enabled = 0;
    s_sb_state_valid = 0;
    s_sb_setup_mode = 0;
    s_sb_deployed_mode = 0;
    s_sb_audit_mode = 0;
    s_sb_pk_present = 0;
    s_sb_kek_present = 0;

    if (!s_available) {
        klog(LOG_INFO, "UEFI", "Secure Boot: unknown (runtime unavailable)");
        /* v18: explicitly publish a degraded trust posture when the
         * runtime is unavailable. Otherwise the BSS-zero g_boot_info
         * leaves degraded_trust_flags=0 (false-clean), which the
         * Registry populator then surfaces as DegradedTrustNames=
         * "clean" -- exactly the false-attestation surface the v18
         * trust-landscape plumbing exists to prevent. We cannot tell
         * SecureBoot/SBAT/dbx state without runtime services, so set
         * the three "we cannot tell" bits. */
        g_boot_info.sbat_level[0] = '\0';
        g_boot_info.sbat_level_size = 0;
        g_boot_info.dbx_size = 0;
        g_boot_info.degraded_trust_flags =
            BOOT_DEGRADED_TRUST_SECURE_BOOT_UNREADABLE |
            BOOT_DEGRADED_TRUST_SBAT_ABSENT |
            BOOT_DEGRADED_TRUST_DBX_ABSENT;
        return BOOT_DEGRADED;
    }

    /* Read SecureBoot variable (uint8_t: 0=off, 1=on) */
    static const uint16_t sb_name[] = {
        'S','e','c','u','r','e','B','o','o','t', 0
    };
    int sb_val = read_global_byte(sb_name);
    int sb_val_valid = (sb_val >= 0);
    if (sb_val_valid) {
        s_sb_enabled = (sb_val == 1) ? 1 : 0;
        s_sb_state_valid = 1;
    }

    /* Read SetupMode variable (uint8_t: 0=User Mode, 1=Setup Mode) */
    static const uint16_t sm_name[] = {
        'S','e','t','u','p','M','o','d','e', 0
    };
    int sm_val = read_global_byte(sm_name);
    if (sm_val >= 0)
        s_sb_setup_mode = (sm_val == 1) ? 1 : 0;

    /* Read DeployedMode variable (UEFI 2.5+: 0=not deployed, 1=deployed) */
    static const uint16_t dm_name[] = {
        'D','e','p','l','o','y','e','d','M','o','d','e', 0
    };
    int dm_val = read_global_byte(dm_name);
    if (dm_val >= 0)
        s_sb_deployed_mode = (dm_val == 1) ? 1 : 0;

    /* Read AuditMode variable (UEFI 2.5+: 0=off, 1=audit) */
    static const uint16_t am_name[] = {
        'A','u','d','i','t','M','o','d','e', 0
    };
    int am_val = read_global_byte(am_name);
    if (am_val >= 0)
        s_sb_audit_mode = (am_val == 1) ? 1 : 0;

    /* Check PK existence */
    static const uint16_t pk_name[] = { 'P','K', 0 };
    s_sb_pk_present = global_var_exists(pk_name);

    /* Check KEK existence */
    static const uint16_t kek_name[] = { 'K','E','K', 0 };
    s_sb_kek_present = global_var_exists(kek_name);

    /* Log summary. When the SecureBoot variable read FAILED we have
     * no authoritative state -- log UNKNOWN rather than "DISABLED"
     * so operators distinguish "read failure" from "keys not enrolled
     * + user turned it off". */
    if (!sb_val_valid) {
        klog(LOG_WARN, "UEFI",
             "Secure Boot: UNKNOWN (variable read failed; cap degraded)");
    } else if (s_sb_enabled) {
        klog(LOG_INFO, "UEFI", "Secure Boot: ENABLED (%s)",
             s_sb_setup_mode ? "Setup Mode" : "User Mode");
    } else {
        klog(LOG_INFO, "UEFI", "Secure Boot: DISABLED (%s)",
             s_sb_setup_mode ? "Setup Mode" : "User Mode");
    }

    klog(LOG_INFO, "UEFI", "Secure Boot keys: PK=%s, KEK=%s",
         s_sb_pk_present ? "enrolled" : "absent",
         s_sb_kek_present ? "enrolled" : "absent");

    /* Publish state to boot_info and global system state for
     * desktop/tray. Only publish when the read succeeded -- a failed
     * read leaves the fields at their zero-init values, but the
     * authoritative signal for downstream consumers is
     * caps_present & BOOT_CAP_SECURE_BOOT_STATE (which stays
     * degraded below when the read failed). */
    if (sb_val_valid) {
        g_boot_info.secure_boot_enabled = (uint8_t)s_sb_enabled;
        g_system_state.secure_boot       = (uint8_t)s_sb_enabled;
    }

    /* Promote BOOT_CAP_SECURE_BOOT_STATE from degraded to present ONLY
     * when the SecureBoot variable read actually succeeded. A failed
     * read leaves the state unknown -- publishing
     * secure_boot_enabled=0 alongside an "authoritative" cap bit would
     * turn an unreadable firmware query into a false "disabled"
     * answer for downstream attestation. Keep the cap degraded when
     * the read failed so consumers know to treat the state as
     * unknown. */
    if (sb_val_valid) {
        boot_caps_mark_present(BOOT_CAP_SECURE_BOOT_STATE);
    } else {
        klog(LOG_WARN, "UEFI",
             "SecureBoot variable read failed; cap stays degraded (state unknown)");
    }

    /* Canonical one-line summary consumed by monitoring tools */
    if (!sb_val_valid) {
        klog(LOG_WARN, "SecureBoot", "state=UNKNOWN (read failed)");
    } else if (s_sb_enabled) {
        klog(LOG_INFO, "SecureBoot", "state=ENABLED");
    } else {
        klog(LOG_INFO, "SecureBoot", "state=DISABLED (firmware or user override)");
    }

    /* v18: trust-landscape surface (artifact-signing partial-ship
     * subset). Populate sbat_level + dbx_size + degraded_trust_flags
     * into boot_info now that the SecureBoot/SetupMode reads above
     * have settled. The bootloader-side manifest signature path
     * remains blocked on crypto vendor work; this is the
     * non-cryptographic subset that surfaces firmware trust signals
     * to consumers. */
    static const uint16_t sbat_name[] = {
        'S','b','a','t','L','e','v','e','l', 0
    };
    /* SbatLevel lives under SHIM_LOCK_GUID, NOT EFI_GLOBAL_VARIABLE
     * _GUID -- shim writes the cumulative SBAT revocation level into
     * its own namespace (sbat.c in shim project). Reading from the
     * global namespace returns NOT_FOUND on every shim-protected
     * boot, which would falsely raise SBAT_ABSENT in
     * degraded_trust_flags. */
    struct boot_uefi_guid shim_lock = SHIM_LOCK_GUID;
    uint64_t sbat_bytes = read_var_string(&shim_lock, sbat_name,
                                          g_boot_info.sbat_level,
                                          sizeof(g_boot_info.sbat_level));
    g_boot_info.sbat_level_size = (uint32_t)sbat_bytes;

    static const uint16_t dbx_size_name[] = { 'd','b','x', 0 };
    uint64_t dbx_bytes = imgsec_var_size(dbx_size_name);
    if (dbx_bytes > 0xFFFFFFFFu) dbx_bytes = 0xFFFFFFFFu;
    g_boot_info.dbx_size = (uint32_t)dbx_bytes;

    uint32_t trust_flags = 0;
    if (!sb_val_valid)
        trust_flags |= BOOT_DEGRADED_TRUST_SECURE_BOOT_UNREADABLE;
    else if (!s_sb_enabled)
        trust_flags |= BOOT_DEGRADED_TRUST_SECURE_BOOT_OFF;
    if (s_sb_setup_mode)
        trust_flags |= BOOT_DEGRADED_TRUST_SETUP_MODE;
    if (sbat_bytes == 0)
        trust_flags |= BOOT_DEGRADED_TRUST_SBAT_ABSENT;
    if (dbx_bytes == 0)
        trust_flags |= BOOT_DEGRADED_TRUST_DBX_ABSENT;

    /* Producer-side closed-mask fail-safe: any out-of-mask bit here
     * indicates a producer bug (typo, future bit not synced into
     * MASK_KNOWN, or memory corruption). The Phase-0 validator's
     * matching gate runs BEFORE this producer in current init order
     * and cannot catch a stray bit from this code path -- without
     * this check the Registry would persist a bit the bit-name
     * iterator silently omits, hiding the real trust posture from
     * attestation tooling. Clamp + LOG_ERROR rather than boot_halt:
     * the trust surface degrading to a documented subset is
     * preferable to refusing to boot. */
    uint32_t out_of_mask = trust_flags & ~(uint32_t)BOOT_DEGRADED_TRUST_MASK_KNOWN;
    if (out_of_mask != 0u) {
        klog(LOG_ERROR, "UEFI",
             "trust-landscape producer set out-of-mask bits 0x%x; clamping to MASK_KNOWN 0x%x",
             (uint64_t)out_of_mask,
             (uint64_t)(uint32_t)BOOT_DEGRADED_TRUST_MASK_KNOWN);
        trust_flags &= (uint32_t)BOOT_DEGRADED_TRUST_MASK_KNOWN;
    }
    g_boot_info.degraded_trust_flags = trust_flags;

    if (sbat_bytes > 0)
        klog(LOG_INFO, "UEFI", "SbatLevel: %u bytes (level=%s)",
             (uint32_t)sbat_bytes, g_boot_info.sbat_level);
    else
        klog(LOG_INFO, "UEFI", "SbatLevel: absent");
    if (dbx_bytes > 0)
        klog(LOG_INFO, "UEFI", "dbx: present (%u bytes)",
             (uint32_t)dbx_bytes);
    else
        klog(LOG_INFO, "UEFI", "dbx: absent");
    if (trust_flags) {
        klog(LOG_WARN, "UEFI",
             "trust-landscape degraded: 0x%x", (uint64_t)trust_flags);
        uint32_t bit;
        for (bit = 1u;
             bit != 0u && bit <= (uint32_t)BOOT_DEGRADED_TRUST_MASK_KNOWN;
             bit <<= 1) {
            if ((trust_flags & bit) == 0u) continue;
            klog(LOG_WARN, "UEFI",
                 "  trust-landscape: %s (advisory; non-fatal)",
                 (uint64_t)(uintptr_t)boot_degraded_trust_bit_name(bit));
        }
    }

    /* Freeze the boot-time state vector so future revalidation passes
     * (S3 resume / periodic tick) can detect firmware drift. Capture
     * even on the unauthoritative path -- the revalidation logic gates
     * on snapshot.sb_state_valid before raising drift. */
    uefi_secureboot_snapshot();

    return BOOT_OK;
}

/* Enforce write-XOR-execute on UEFI runtime memory regions by walking the
 * EFI_MEMORY_ATTRIBUTES_TABLE (TODO-04 sec5 consumer API) and flipping kernel
 * page-table permissions: DATA/RODATA -> NX, CODE -> RO. Runtime regions are
 * identity-mapped (SetVirtualAddressMap virtual_start = phys_addr) so the MAT
 * phys_addr is the virtual address. Runs ONCE, single-threaded, before SMP AP
 * bring-up. TODO-27 sec3.
 *
 * Fail-closed accounting: the success log is a hard claim that
 * every applicable runtime page is W^X. It is emitted ONLY when nothing failed
 * and no firmware-declared W^X violation remains; otherwise the degraded
 * accounting is logged. WX_VIOLATION regions are left intact (forcing them would
 * break firmware) and counted as an unsafe residual.
 *
 * The static MAT freezes attributes at boot; the runtime
 * EFI_MEMORY_ATTRIBUTE_PROTOCOL sync (TODO-27 sec3, deferred -- needs a boot_info
 * ABI add) is absent, so this is static enforcement only. */
/* True only if [phys, phys+bytes) lies fully within a single UEFI runtime region
 * (g_boot_info.rt_mmap). The MAT should describe only runtime memory, but a
 * malformed firmware table could point at arbitrary identity-mapped pages
 * (kernel/heap/MMIO) -- flipping NX/RO there would crash the OS. Defense in
 * depth: only mutate page tables for ranges proven runtime (TODO-27 sec3). */
static int mat_range_is_runtime(uint64_t phys, uint64_t bytes)
{
    uint32_t i, n = g_boot_info.rt_mmap_count;
    uint64_t end;
    if (bytes == 0 || phys + bytes < phys)
        return 0;
    end = phys + bytes;
    if (n > BOOT_RT_MMAP_MAX)
        n = BOOT_RT_MMAP_MAX;
    for (i = 0; i < n; i++) {
        uint64_t rstart = g_boot_info.rt_mmap[i].phys_addr;
        uint64_t rpages = g_boot_info.rt_mmap[i].num_pages;
        uint64_t rend;
        if (rpages == 0 || rpages > (0xFFFFFFFFFFFFFFFFull / 4096u))
            continue;
        rend = rstart + rpages * 4096u;
        if (rend < rstart)
            continue;
        if (phys >= rstart && end <= rend)
            return 1;
    }
    return 0;
}

void uefi_runtime_enforce_wx(void)
{
    uint32_t n, i;
    uint32_t enforced = 0, skipped = 0, failed = 0, wxviol = 0, nonrt = 0;

    /* Boot-order guard: the per-page vmm TLB flush is a local
     * invlpg, correct only while a single CPU runs. Refuse enforcement once SMP
     * is up rather than mutate page tables without a TLB shootdown. */
    if (kernel_subsystem_ready(SUBSYS_SMP) || smp_cpu_count() > 1) {
        klog(LOG_ERROR, "UEFI",
             "W^X enforcement refused: SMP active (no TLB shootdown)");
        return;
    }

    n = mat_get_count();
    if (n == 0) {
        klog(LOG_WARN, "UEFI",
             "W^X: no EFI_MEMORY_ATTRIBUTES_TABLE -- enforcement skipped");
        return;
    }

    for (i = 0; i < n; i++) {
        mat_entry_t e;
        uint64_t bytes;
        int rc;
        if (mat_get_entry(i, &e) == 0) { failed++; continue; }  /* 1 = success */
        bytes = (uint64_t)e.num_pages * 4096u;
        /* Reject a MAT entry that does not lie within a runtime region -- a
         * malformed firmware table must not drive NX/RO on kernel/heap/MMIO. */
        if (!mat_range_is_runtime(e.phys_addr, bytes)) {
            nonrt++;
            continue;
        }
        switch (e.cls) {
        case MAT_CLASS_DATA:
        case MAT_CLASS_RODATA:
            rc = vmm_set_nx((uintptr_t)e.phys_addr, bytes);
            if (rc == 0) enforced++; else failed++;
            break;
        case MAT_CLASS_CODE:
            rc = vmm_set_ro((uintptr_t)e.phys_addr, bytes);
            if (rc == 0) enforced++; else failed++;
            break;
        case MAT_CLASS_WX_VIOLATION:
            wxviol++;                 /* firmware W+X: cannot fix without breaking it */
            break;
        case MAT_CLASS_GUARD:
        default:
            skipped++;                /* not-present / unknown: nothing to enforce */
            break;
        }
    }

    if (failed == 0 && wxviol == 0 && nonrt == 0) {
        klog(LOG_INFO, "UEFI",
             "W^X enforced on %u runtime memory regions (static MAT)", enforced);
    } else {
        klog(LOG_WARN, "UEFI",
             "W^X DEGRADED: %u enforced, %u failed, %u W^X-violation, "
             "%u non-runtime, %u skipped",
             enforced, failed, wxviol, nonrt, skipped);
    }
}

/* Called from registry_populate_defaults() after registry_init() -- writes
 * HKLM\SYSTEM\SecureBoot\State once the registry tree is ready. */
void uefi_secureboot_populate_registry(void)
{
    HKEY hKey;
    if (RegCreateKeyEx(HKEY_LOCAL_MACHINE, "SYSTEM\\SecureBoot", 0,
                       NULL, 0, KEY_WRITE, NULL, &hKey, NULL) == ERROR_SUCCESS) {
        const struct secureboot_db_info *dbi = secureboot_get_db_info();
        /* Gate State on read validity.  StateValid=0 means the
         * SecureBoot variable read failed; State is meaningless in
         * that case.  We write StateValid always, but write State
         * ONLY when valid.  Do NOT write a sentinel value for State
         * on the invalid path -- a truthy 0xFF would pollute the
         * existing State=0|1 boolean contract for legacy consumers.
         * Consumers MUST check StateValid first; if they read State
         * directly they get key-not-found (which they must handle
         * explicitly, not coerce to "false"). */
        RegSetDword(hKey, "StateValid",   (uint32_t)s_sb_state_valid);
        if (s_sb_state_valid) {
            RegSetDword(hKey, "State",    (uint32_t)s_sb_enabled);
        }
        RegSetDword(hKey, "SetupMode",   (uint32_t)s_sb_setup_mode);
        RegSetDword(hKey, "DeployedMode",(uint32_t)s_sb_deployed_mode);
        RegSetDword(hKey, "AuditMode",   (uint32_t)s_sb_audit_mode);
        RegSetDword(hKey, "PKEnrolled",  (uint32_t)s_sb_pk_present);
        RegSetDword(hKey, "KEKEnrolled", (uint32_t)s_sb_kek_present);
        /* Mirror db/dbx inventory from secureboot_keys_init() (S9) */
        if (dbi) {
            RegSetDword(hKey, "DbEntries",  dbi->db_entries);
            RegSetDword(hKey, "DbxEntries", dbi->dbx_entries);
            RegSetDword(hKey, "DbSha256",   dbi->db_sha256_count);
            RegSetDword(hKey, "DbxSha256",  dbi->dbx_sha256_count);
            RegSetDword(hKey, "DbX509",     dbi->db_x509_count);
        }
        /* MS UEFI CA generation tracking. ShimCA surfaces which
         * Microsoft Corporation UEFI CA the bundled shim binary is
         * signed against, for audit tools (msinfo32-equivalent /
         * security inventory / support diagnostics).
         *
         * Sentinel values (Codex design Q4 fix 2026-04-29):
         *   0          = shim binary not pinned in-tree (current
         *                state -- waiting on Microsoft to publish the
         *                2023-CA-signed shim)
         *   0xFFFFFFFF = shim present but sbverify could not identify
         *                the CA generation (build-time parse failure)
         *   2011|2023  = sbverify-confirmed CA year, embedded as a
         *                build-time constant SHA-bound to the pinned
         *                shim binary at image-build time
         *
         * Path forward when shim/shimx64.efi gets pinned: the build
         * script extracts the CA year via `sbverify --list` and writes
         * it into a generated header consumed here. See
         * docs/guides/secure-boot-keys.md "MS UEFI CA Lifecycle". */
        /* Read the actual CA year from the build-time generated
         * header (extracted by scripts/extract-shim-ca.sh from
         * `sbverify --list shim/shimx64.efi`).  Reports 2011 /
         * 2023 / 0xFFFFFFFF / 0 per the sentinel doctrine above. */
        RegSetDword(hKey, "ShimCA", SHIM_CA_YEAR);
        RegCloseKey(hKey);
        klog(LOG_DEBUG, "SecureBoot",
             "HKLM\\SYSTEM\\SecureBoot: State=%u Db=%u Dbx=%u",
             (uint64_t)s_sb_enabled,
             dbi ? (uint64_t)dbi->db_entries : 0,
             dbi ? (uint64_t)dbi->dbx_entries : 0);
    }
}

int uefi_secureboot_enabled(void)  { return s_sb_enabled; }

int uefi_secureboot_state_valid(void)
{
    /* The Secure Boot variable read either succeeded (cap promoted from
     * degraded to present at boot) or failed (cap stays in caps_degraded).
     * Reading caps_degraded gives the authoritative answer without us
     * having to track a second `s_sb_state_valid` flag.  Centralizing the
     * predicate here means consumers never accidentally read s_sb_enabled
     * (which is 0 for both DISABLED and UNREADABLE) without first checking
     * validity. */
    return (g_boot_info.caps_degraded & BOOT_CAP_SECURE_BOOT_STATE) ? 0 : 1;
}

int uefi_secureboot_setup_mode(void) { return s_sb_setup_mode; }
int uefi_secureboot_pk_present(void) { return s_sb_pk_present; }
int uefi_secureboot_kek_present(void) { return s_sb_kek_present; }

/* ----- Runtime Secure Boot revalidation (gap-audit 2026-05-01 M2) -----
 *
 * Boot-time snapshot of the authoritative SecureBoot state. After
 * uefi_secureboot_init() succeeds we freeze the state vector here;
 * uefi_secureboot_revalidate_tick() compares the current live values
 * against this snapshot and raises a LOG_FATAL + sets the registry
 * sentinel HKLM\SYSTEM\SecureBoot\Drift on any mismatch. A drift
 * signals firmware compromise, NVRAM corruption, or a physical
 * attacker clearing SetupMode while the OS slept.
 *
 * Concurrency: the s_sb_* statics are read/mutated by uefi_secureboot_*
 * paths only; uefi_secureboot_init() runs strictly before any thread
 * is created so the snapshot capture there does not race. After init,
 * uefi_secureboot_refresh() (S3 resume / periodic) can mutate and any
 * concurrent reader on another CPU could see a torn read. Serialize
 * the post-init refresh + comparison under s_sb_lock; the per-byte
 * accessors stay lock-free for legacy callers because torn reads on
 * a uint8_t-sized field are atomic on x86-64. */

struct sb_state_vector {
    int sb_state_valid; /* SecureBoot variable read succeeded */
    int sb_enabled;
    int setup_mode;
    int deployed_mode;
    int audit_mode;
    int pk_present;
    int kek_present;
};

static struct sb_state_vector s_sb_snapshot;
static int s_sb_snapshot_valid; /* 1 once uefi_secureboot_init captured the snapshot */

/* Drift detection is sticky once observed; registry publication is
 * tracked separately so a transient registry write failure on the
 * first tick does not permanently suppress the sentinel. Codex
 * adversarial 2026-05-01 H1 fix. */
static int s_sb_drift_detected;
static int s_sb_drift_published;
static DEFINE_SPINLOCK(s_sb_lock);

/* Tri-state byte read: returns 1 if `*out` was set from a definitive
 * SUCCESS read, 0 if the variable was definitively NOT_FOUND, -1 if
 * the read was indeterminate (UNSUPPORTED, transient firmware error,
 * SUCCESS with wrong size, etc.). Codex re-adversarial 2026-05-01 H2
 * fix: a -1 return must NOT be collapsed to "field is zero" by the
 * caller -- that would let a transient firmware hiccup trigger a
 * false drift event. */
static int read_global_byte_status(const uint16_t *name, uint8_t *out)
{
    struct boot_uefi_guid global = EFI_GLOBAL_VARIABLE_GUID;
    uint8_t val = 0;
    uint64_t sz = sizeof(val);
    uint32_t attrs = 0;

    efi_status_t status = uefi_get_variable(&global, name, &attrs, &sz, &val);
    if (status == UEFI_SUCCESS && sz == sizeof(val)) {
        *out = val;
        return 1;
    }
    if (status == UEFI_NOT_FOUND)
        return 0;
    return -1;
}

/* Tri-state existence check: returns 1 if the variable definitively
 * exists with non-zero data, 0 if it definitively does NOT exist
 * (UEFI_NOT_FOUND, or empty SUCCESS-with-sz=0 which we treat as
 * not-enrolled), -1 if the result is indeterminate.  Distinguishing
 * NOT_FOUND from a read failure prevents drift detection from
 * flipping pk_present/kek_present from 1 to 0 on a transient
 * hiccup. */
static int global_var_exists_status(const uint16_t *name)
{
    struct boot_uefi_guid global = EFI_GLOBAL_VARIABLE_GUID;
    uint64_t sz = 0;
    uint32_t attrs = 0;

    efi_status_t status = uefi_get_variable(
        &global, name, &attrs, &sz, (void *)0);

    if (status == UEFI_BUFFER_TOO_SMALL && sz > 0) return 1;
    if (status == UEFI_SUCCESS && sz > 0)          return 1;
    if (status == UEFI_NOT_FOUND)                  return 0;
    if (status == UEFI_SUCCESS && sz == 0)         return 0;
    return -1;
}

/* Read every SecureBoot UEFI variable into a local state vector.
 * MUST be called WITHOUT s_sb_lock held -- uefi_get_variable()
 * acquires the sleepable s_rt_mutex via rt_call_enter(), and a
 * mutex must never be acquired under a spinlock with IRQs disabled.
 * The s_rt_mutex itself serializes firmware calls.  Returns 1 if
 * EVERY tracked field was read with a definitive status (vector is
 * fully authoritative), 0 if any field's read was indeterminate
 * (caller MUST skip drift comparison and legacy accessor updates). */
static int uefi_secureboot_read_locked_state(struct sb_state_vector *out)
{
    static const uint16_t sb_name[]  = { 'S','e','c','u','r','e','B','o','o','t', 0 };
    static const uint16_t sm_name[]  = { 'S','e','t','u','p','M','o','d','e', 0 };
    static const uint16_t dm_name[]  = { 'D','e','p','l','o','y','e','d','M','o','d','e', 0 };
    static const uint16_t am_name[]  = { 'A','u','d','i','t','M','o','d','e', 0 };
    static const uint16_t pk_name[]  = { 'P','K', 0 };
    static const uint16_t kek_name[] = { 'K','E','K', 0 };

    uint8_t b;
    int s_sb, s_sm, s_dm, s_am, s_pk, s_kek;

    out->sb_state_valid = 0;
    out->sb_enabled     = 0;
    out->setup_mode     = 0;
    out->deployed_mode  = 0;
    out->audit_mode     = 0;
    out->pk_present     = 0;
    out->kek_present    = 0;

    s_sb = read_global_byte_status(sb_name, &b);
    if (s_sb == 1) {
        out->sb_enabled     = (b == 1) ? 1 : 0;
        out->sb_state_valid = 1;
    }

    s_sm = read_global_byte_status(sm_name, &b);
    if (s_sm == 1) out->setup_mode = (b == 1) ? 1 : 0;

    s_dm = read_global_byte_status(dm_name, &b);
    if (s_dm == 1) out->deployed_mode = (b == 1) ? 1 : 0;

    s_am = read_global_byte_status(am_name, &b);
    if (s_am == 1) out->audit_mode = (b == 1) ? 1 : 0;

    s_pk = global_var_exists_status(pk_name);
    if (s_pk >= 0) out->pk_present = s_pk;

    s_kek = global_var_exists_status(kek_name);
    if (s_kek >= 0) out->kek_present = s_kek;

    /* Authoritative iff every tracked read was definitive. Any
     * indeterminate read (-1) on any field disqualifies the vector
     * from drift comparison and legacy accessor publication. */
    if (s_sb < 0 || s_sm < 0 || s_dm < 0 || s_am < 0 ||
        s_pk < 0 || s_kek < 0)
        return 0;
    return 1;
}

void uefi_secureboot_snapshot(void)
{
    uint64_t flags;
    spin_lock_irqsave(&s_sb_lock, &flags);
    s_sb_snapshot.sb_state_valid = s_sb_state_valid;
    s_sb_snapshot.sb_enabled     = s_sb_enabled;
    s_sb_snapshot.setup_mode     = s_sb_setup_mode;
    s_sb_snapshot.deployed_mode  = s_sb_deployed_mode;
    s_sb_snapshot.audit_mode     = s_sb_audit_mode;
    s_sb_snapshot.pk_present     = s_sb_pk_present;
    s_sb_snapshot.kek_present    = s_sb_kek_present;
    s_sb_snapshot_valid          = 1;
    spin_unlock_irqrestore(&s_sb_lock, flags);
}

/* Write HKLM\SYSTEM\SecureBoot\Drift = 1 to flag firmware tampering
 * for monitoring tools.  Returns 1 on success, 0 on failure -- the
 * caller uses the result to decide whether to retry on the next
 * tick (registry not yet ready when the first drift is observed
 * must not permanently suppress the sentinel). */
static int uefi_secureboot_publish_drift(void)
{
    HKEY hKey;
    if (RegCreateKeyEx(HKEY_LOCAL_MACHINE, "SYSTEM\\SecureBoot", 0,
                       NULL, 0, KEY_WRITE, NULL, &hKey, NULL) != ERROR_SUCCESS)
        return 0;
    long err = RegSetDword(hKey, "Drift", 1);
    RegCloseKey(hKey);
    return err == ERROR_SUCCESS;
}

/* Read live UEFI state, compare against the boot snapshot, and
 * emit + publish a drift signal on first observed mismatch. Returns
 * 1 if drift was detected (this call OR any prior call -- the
 * detection is sticky), 0 otherwise. Returns 0 also when runtime
 * services are unavailable, the snapshot has not been captured, or
 * either read was unauthoritative -- those cases are silent so a
 * transient firmware hiccup does not raise a false alarm. */
static int uefi_secureboot_do_revalidate(void)
{
    struct sb_state_vector live;
    struct sb_state_vector snapshot_copy;
    uint64_t flags;
    int drifted_now = 0;
    int drift_was_already_detected;
    int needs_publish;
    int published_ok = 0;
    int live_authoritative;

    if (!s_available)
        return 0;

    /* Read firmware state OUTSIDE s_sb_lock. uefi_get_variable
     * acquires s_rt_mutex (sleepable) which must never run under a
     * spinlock with IRQs disabled. */
    live_authoritative = uefi_secureboot_read_locked_state(&live);

    spin_lock_irqsave(&s_sb_lock, &flags);

    if (!s_sb_snapshot_valid) {
        spin_unlock_irqrestore(&s_sb_lock, flags);
        return 0;
    }

    /* Publish live state to the legacy s_sb_* statics so
     * uefi_secureboot_enabled() etc. observe post-resume values --
     * but only when EVERY field was read with a definitive status
     * AND the SecureBoot variable read succeeded (Codex
     * re-adversarial 2026-05-01 H2: a transient firmware hiccup on
     * any non-SecureBoot field must not overwrite the previously
     * authoritative state). */
    if (live_authoritative && live.sb_state_valid) {
        s_sb_state_valid   = 1;
        s_sb_enabled       = live.sb_enabled;
        s_sb_setup_mode    = live.setup_mode;
        s_sb_deployed_mode = live.deployed_mode;
        s_sb_audit_mode    = live.audit_mode;
        s_sb_pk_present    = live.pk_present;
        s_sb_kek_present   = live.kek_present;
    }

    /* Boot snapshot was unauthoritative, live read had any
     * indeterminate field, or the live SecureBoot read failed: no
     * baseline / no comparable state -- skip the drift comparison.
     * The sticky s_sb_drift_detected flag is returned unchanged so
     * a real drift latched on a previous tick stays latched. */
    if (!s_sb_snapshot.sb_state_valid || !live_authoritative ||
        !live.sb_state_valid) {
        int sticky = s_sb_drift_detected;
        spin_unlock_irqrestore(&s_sb_lock, flags);
        return sticky;
    }

    if (live.sb_enabled      != s_sb_snapshot.sb_enabled    ||
        live.setup_mode      != s_sb_snapshot.setup_mode    ||
        live.deployed_mode   != s_sb_snapshot.deployed_mode ||
        live.audit_mode      != s_sb_snapshot.audit_mode    ||
        live.pk_present      != s_sb_snapshot.pk_present    ||
        live.kek_present     != s_sb_snapshot.kek_present) {
        drifted_now = 1;
    }

    drift_was_already_detected = s_sb_drift_detected;
    if (drifted_now)
        s_sb_drift_detected = 1;

    /* Retry registry publication on every call where drift is
     * latched but the sentinel write has not yet been confirmed.
     * Publishing only on the detection edge means a single failed
     * write (e.g. registry not yet ready) leaves the sentinel
     * permanently un-published. */
    needs_publish = s_sb_drift_detected && !s_sb_drift_published;
    snapshot_copy = s_sb_snapshot;

    spin_unlock_irqrestore(&s_sb_lock, flags);

    if (drifted_now && !drift_was_already_detected) {
        klog(LOG_FATAL, "SecureBoot",
             "DRIFT detected: boot snapshot SB=%u SM=%u DM=%u AM=%u PK=%u KEK=%u "
             "vs live SB=%u SM=%u DM=%u AM=%u PK=%u KEK=%u "
             "(firmware compromise, NVRAM corruption, or physical attack)",
             (uint64_t)snapshot_copy.sb_enabled,
             (uint64_t)snapshot_copy.setup_mode,
             (uint64_t)snapshot_copy.deployed_mode,
             (uint64_t)snapshot_copy.audit_mode,
             (uint64_t)snapshot_copy.pk_present,
             (uint64_t)snapshot_copy.kek_present,
             (uint64_t)live.sb_enabled,
             (uint64_t)live.setup_mode,
             (uint64_t)live.deployed_mode,
             (uint64_t)live.audit_mode,
             (uint64_t)live.pk_present,
             (uint64_t)live.kek_present);
    }

    if (needs_publish) {
        published_ok = uefi_secureboot_publish_drift();
        if (published_ok) {
            spin_lock_irqsave(&s_sb_lock, &flags);
            s_sb_drift_published = 1;
            spin_unlock_irqrestore(&s_sb_lock, flags);
        } else {
            klog(LOG_WARN, "SecureBoot",
                 "drift detected but registry publish failed; will retry next tick");
        }
    }

    return s_sb_drift_detected;
}

int uefi_secureboot_revalidate_tick(void)
{
    return uefi_secureboot_do_revalidate();
}

int uefi_secureboot_refresh(void)
{
    return uefi_secureboot_do_revalidate();
}

int uefi_secureboot_drift_detected(void)
{
    return s_sb_drift_detected;
}

/* kworker callback shim: the periodic worker pool takes a void(*)(void*)
 * callback, but the revalidate tick is int(void). */
static void uefi_secureboot_revalidate_worker(void *ctx)
{
    (void)ctx;
    (void)uefi_secureboot_revalidate_tick();
}

/* Register the post-boot SecureBoot drift monitor on the system worker pool:
 * re-checks the live SecureBoot/PK/KEK/db/dbx state against the boot-time
 * snapshot every 5 minutes to catch firmware drift / NVRAM corruption /
 * physical-attack tampering that happens after boot. Bounded (one variable
 * read set per tick), so it respects the kworker bounded-callback contract. */
void uefi_secureboot_register_monitor(void)
{
    int token = kworker_register(uefi_secureboot_revalidate_worker, (void *)0,
                                 5u * 60u * 1000u);   /* 5 minutes */
    if (token < 0)
        klog(LOG_WARN, "UEFI",
             "SecureBoot drift monitor not registered (no kworker slot)");
    else
        klog(LOG_INFO, "UEFI", "SecureBoot drift monitor armed (5 min cadence)");
}

/* Surface QueryVariableInfo() results to HKLM\SYSTEM\SecureBoot\Vars
 * so post-boot tools can see the firmware variable storage quota
 * (production firmware enforces ~64 KB per machine total). The
 * non-volatile + boot-services + runtime attribute combination is
 * the production-relevant slice (BS-only and runtime-only counters
 * are not separately tracked because Win32 GetFirmwareEnvironmentVariable
 * always uses the NV+BS+RT slice).
 *
 * Validity contract mirrors the HKLM\SYSTEM\SecureBoot\State pattern:
 * always write VarsValid (DWORD 0/1), write the size fields ONLY when
 * QueryVariableInfo succeeded.  A missing size key is "did not query";
 * a present size key is "this is the firmware-reported value".
 * Consumers MUST check VarsValid first.  Sizes use REG_QWORD because
 * the spec is UINT64.
 */
void uefi_runtime_populate_vars_registry(void)
{
    HKEY hKey;
    long rc = RegCreateKeyEx(HKEY_LOCAL_MACHINE,
                              "SYSTEM\\SecureBoot\\Vars", 0,
                              NULL, 0, KEY_WRITE, NULL, &hKey, NULL);
    if (rc != ERROR_SUCCESS) {
        klog(LOG_WARN, "UEFI",
             "Vars registry: RegCreateKeyEx failed");
        return;
    }

    uint64_t max_storage = 0;
    uint64_t remaining = 0;
    uint64_t max_var_size = 0;
    uint32_t attrs = EFI_VARIABLE_NON_VOLATILE |
                     EFI_VARIABLE_BOOTSERVICE_ACCESS |
                     EFI_VARIABLE_RUNTIME_ACCESS;
    uint64_t status = uefi_query_variable_info(attrs, &max_storage,
                                                &remaining, &max_var_size);

    if (status == UEFI_SUCCESS) {
        RegSetDword(hKey, "VarsValid", 1);
        RegSetQword(hKey, "MaxStorageSize",   max_storage);
        RegSetQword(hKey, "RemainingSize",    remaining);
        RegSetQword(hKey, "MaxVariableSize",  max_var_size);
        RegSetDword(hKey, "Attributes",       attrs);
        klog(LOG_INFO, "UEFI",
             "Vars registry: max=%u remain=%u max_var=%u",
             (uint32_t)max_storage, (uint32_t)remaining,
             (uint32_t)max_var_size);
    } else {
        RegSetDword(hKey, "VarsValid", 0);
        klog(LOG_INFO, "UEFI",
             "Vars registry: QueryVariableInfo unavailable (status=0x%x)",
             (uint64_t)status);
    }
    RegCloseKey(hKey);
}

/* ============================================================================
 * Secure Boot Key Management
 *
 * Reads and parses db/dbx/dbt signature databases.
 * Walking EFI_SIGNATURE_LIST chains to enumerate trust entries.
 * Authenticated writes (dbx update) deferred until crypto stack available.
 * ============================================================================ */

static struct secureboot_db_info s_db_info;

/* GUID comparison helper (reuse from uefi_config.c pattern) */
static int sb_guid_equal(const struct boot_uefi_guid *a,
                         const struct boot_uefi_guid *b)
{
    const uint8_t *pa = (const uint8_t *)a;
    const uint8_t *pb = (const uint8_t *)b;
    uint32_t i;
    for (i = 0; i < 16; i++)
        if (pa[i] != pb[i]) return 0;
    return 1;
}

/* Walk an EFI_SIGNATURE_LIST chain in a buffer, counting entries by type. */
static void count_sig_entries(const uint8_t *buf, uint64_t buf_sz,
                              uint32_t *total,
                              uint32_t *sha256_count,
                              uint32_t *x509_count)
{
    struct boot_uefi_guid sha256_type = EFI_CERT_SHA256_GUID;
    struct boot_uefi_guid x509_type   = EFI_CERT_X509_GUID;

    *total = 0;
    *sha256_count = 0;
    *x509_count = 0;

    uint64_t offset = 0;
    while (offset + sizeof(struct efi_signature_list) <= buf_sz) {
        const struct efi_signature_list *sl =
            (const struct efi_signature_list *)(buf + offset);

        if (sl->signature_list_size == 0) break;
        if (offset + sl->signature_list_size > buf_sz) break;

        /* Firmware/NVRAM-supplied sizes are untrusted.
         * signature_list_size could be smaller than header +
         * signature_header_size, which would underflow the
         * subtraction below and fabricate a huge entries count.
         * Compute header_total as uint64 so a hostile
         * signature_header_size near UINT32_MAX cannot wrap before
         * the comparison. */
        uint64_t header_total = (uint64_t)sizeof(struct efi_signature_list)
            + (uint64_t)sl->signature_header_size;
        if ((uint64_t)sl->signature_list_size < header_total) break;
        if (sl->signature_size < sizeof(struct efi_signature_data)) break;
        uint32_t data_size = sl->signature_list_size - (uint32_t)header_total;
        /* data_size must be an exact multiple of signature_size for
         * a well-formed list -- treat any remainder as malformed. */
        if (data_size % sl->signature_size != 0) break;
        uint32_t entries = data_size / sl->signature_size;

        *total += entries;

        if (sb_guid_equal(&sl->signature_type, &sha256_type))
            *sha256_count += entries;
        else if (sb_guid_equal(&sl->signature_type, &x509_type))
            *x509_count += entries;

        offset += sl->signature_list_size;
    }
}

/* Read a security database variable and count its entries. */
static void read_security_db(const uint16_t *name,
                             uint32_t *total,
                             uint32_t *sha256_count,
                             uint32_t *x509_count)
{
    struct boot_uefi_guid db_guid = EFI_IMAGE_SECURITY_DATABASE_GUID;
    uint32_t attrs = 0;

    *total = 0;
    *sha256_count = 0;
    *x509_count = 0;

    /* First call with size=0 to get actual size */
    uint64_t sz = 0;
    efi_status_t status = uefi_get_variable(
        &db_guid, name, &attrs, &sz, (void *)0);

    if (status != UEFI_BUFFER_TOO_SMALL || sz == 0)
        return;  /* Variable doesn't exist or is empty */

    /* Use a static buffer -- security DBs are typically 1-4 KB in OVMF,
     * up to ~32 KB on real hardware with many entries.
     * We cap at 8 KB to avoid stack overflow. */
    if (sz > 8192) sz = 8192;

    uint8_t dbuf[8192];
    status = uefi_get_variable(&db_guid, name, &attrs, &sz, dbuf);
    if (status != UEFI_SUCCESS)
        return;

    count_sig_entries(dbuf, sz, total, sha256_count, x509_count);
}

void secureboot_keys_init(void)
{
    uint32_t i;
    uint8_t *p = (uint8_t *)&s_db_info;
    for (i = 0; i < (uint32_t)sizeof(s_db_info); i++)
        p[i] = 0;

    if (!s_available) return;

    /* Read db (Authorized Signature Database) */
    static const uint16_t db_name[] = { 'd','b', 0 };
    uint32_t db_sha = 0, db_x509 = 0;
    read_security_db(db_name, &s_db_info.db_entries, &db_sha, &db_x509);
    s_db_info.db_sha256_count = db_sha;
    s_db_info.db_x509_count = db_x509;

    /* Read dbx (Forbidden Signature Database) */
    static const uint16_t dbx_name[] = { 'd','b','x', 0 };
    uint32_t dbx_sha = 0, dbx_x509 = 0;
    read_security_db(dbx_name, &s_db_info.dbx_entries, &dbx_sha, &dbx_x509);
    s_db_info.dbx_sha256_count = dbx_sha;

    /* Read dbt (Timestamp Database) */
    static const uint16_t dbt_name[] = { 'd','b','t', 0 };
    uint32_t dbt_sha = 0, dbt_x509 = 0;
    read_security_db(dbt_name, &s_db_info.dbt_entries, &dbt_sha, &dbt_x509);

    /* Log summary */
    klog(LOG_INFO, "UEFI", "Secure Boot db: %u entries "
         "(%u X.509, %u SHA-256)",
         s_db_info.db_entries,
         s_db_info.db_x509_count,
         s_db_info.db_sha256_count);

    klog(LOG_INFO, "UEFI", "Secure Boot dbx: %u revocations "
         "(%u SHA-256)",
         s_db_info.dbx_entries,
         s_db_info.dbx_sha256_count);

    if (s_db_info.dbt_entries > 0) {
        klog(LOG_INFO, "UEFI", "Secure Boot dbt: %u timestamp entries",
             s_db_info.dbt_entries);
    }
}

const struct secureboot_db_info *secureboot_get_db_info(void)
{
    return &s_db_info;
}

/* ============================================================================
 * Crypto Agility (§5.3 -- UEFI 2.10)
 *
 * Reads the CryptoIndication variables to determine firmware algorithm
 * capabilities and active negotiated set.  These variables enable OS-driven
 * algorithm upgrades (e.g., SHA-256 → SHA-384) without firmware reflash.
 *
 * Variable names (all under EFI_GLOBAL_VARIABLE GUID):
 *   "CryptoIndicationsSupported" -- firmware lists everything it can do
 *   "CryptoIndications"          -- OS writes what it wants for next boot
 *   "CryptoIndicationsActivated" -- firmware confirms what's active now
 *
 * OVMF/EDK2 does not currently implement these (UEFI 2.10 is new), so
 * this will gracefully report "not available" on most test platforms.
 * ============================================================================ */

static struct crypto_agility_info s_crypto_info;

/* Read a uint32_t UEFI variable by UCS-2 name (global GUID). */
static uint32_t read_crypto_var(const uint16_t *name)
{
    struct boot_uefi_guid global = EFI_GLOBAL_VARIABLE_GUID;
    uint32_t attrs = 0;
    uint32_t val = 0;
    uint64_t sz = sizeof(val);
    efi_status_t status = uefi_get_variable(
        &global, name, &attrs, &sz, &val);
    if (status != UEFI_SUCCESS) return 0;
    return val;
}

/* Append algorithm name to buffer if bitmask bit is set. */
static int append_algo(char *buf, int pos, int max,
                       uint32_t mask, uint32_t bit, const char *name)
{
    if (!(mask & bit)) return pos;
    if (pos > 0 && pos < max - 1)
        buf[pos++] = '+';
    int i = 0;
    while (name[i] && pos < max - 1)
        buf[pos++] = name[i++];
    buf[pos] = '\0';
    return pos;
}

void uefi_crypto_agility_init(void)
{
    uint32_t i;
    uint8_t *p = (uint8_t *)&s_crypto_info;
    for (i = 0; i < (uint32_t)sizeof(s_crypto_info); i++)
        p[i] = 0;

    if (!s_available) return;

    /* Read CryptoIndicationsSupported (firmware-owned) */
    static const uint16_t name_sup[] = {
        'C','r','y','p','t','o','I','n','d','i','c','a','t','i','o','n','s',
        'S','u','p','p','o','r','t','e','d', 0 };
    s_crypto_info.supported = read_crypto_var(name_sup);

    /* If firmware doesn't support CryptoIndications, skip the rest */
    if (s_crypto_info.supported == 0) {
        klog(LOG_INFO, "UEFI",
             "Crypto agility: not available "
             "(firmware lacks UEFI 2.10 CryptoIndications)");
        return;
    }

    s_crypto_info.available = 1;

    /* Read CryptoIndications (OS-owned -- what we previously requested) */
    static const uint16_t name_req[] = {
        'C','r','y','p','t','o','I','n','d','i','c','a','t','i','o','n','s',
        0 };
    s_crypto_info.requested = read_crypto_var(name_req);

    /* Read CryptoIndicationsActivated (firmware-owned -- what's active now) */
    static const uint16_t name_act[] = {
        'C','r','y','p','t','o','I','n','d','i','c','a','t','i','o','n','s',
        'A','c','t','i','v','a','t','e','d', 0 };
    s_crypto_info.activated = read_crypto_var(name_act);

    /* Log what's active */
    char active_str[64];
    int pos = 0;
    active_str[0] = '\0';
    pos = append_algo(active_str, pos, 64,
                      s_crypto_info.activated,
                      CRYPTO_IND_RSA_4096_SHA512, "RSA-4096");
    pos = append_algo(active_str, pos, 64,
                      s_crypto_info.activated,
                      CRYPTO_IND_RSA_3072_SHA384, "RSA-3072");
    pos = append_algo(active_str, pos, 64,
                      s_crypto_info.activated,
                      CRYPTO_IND_ECDSA_P384, "ECDSA-P384");
    pos = append_algo(active_str, pos, 64,
                      s_crypto_info.activated,
                      CRYPTO_IND_ECDSA_P256, "ECDSA-P256");
    pos = append_algo(active_str, pos, 64,
                      s_crypto_info.activated,
                      CRYPTO_IND_RSA_2048_SHA256, "RSA-2048");
    pos = append_algo(active_str, pos, 64,
                      s_crypto_info.activated,
                      CRYPTO_IND_SHA384, "SHA-384");
    pos = append_algo(active_str, pos, 64,
                      s_crypto_info.activated,
                      CRYPTO_IND_SHA256, "SHA-256");
    (void)pos;

    if (active_str[0] != '\0') {
        klog(LOG_INFO, "UEFI",
             "Crypto agility: active [%s], %u supported, %u requested",
             active_str,
             s_crypto_info.supported,
             s_crypto_info.requested);
    } else {
        klog(LOG_INFO, "UEFI",
             "Crypto agility: supported=0x%x, none activated yet",
             s_crypto_info.supported);
    }

    /* TODO: When crypto policy engine is built, implement:
     *   1. Analyze supported bitmask to find strongest common set
     *   2. Write CryptoIndications to request upgrade (e.g., SHA-384 + RSA-3072)
     *   3. On next boot, firmware reads our request and activates it
     *   4. Check CryptoIndicationsActivated to confirm upgrade took effect */
}

