/* Draw a single character at pixel position (px, py) on a framebuffer.
 * color: 0x00RRGGBB packed pixel.  Clips silently at screen edges. */
static void blit_char(volatile uint32_t *fb, uint32_t pitch_px,
                      uint32_t fb_w, uint32_t fb_h,
                      uint32_t px, uint32_t py,
                      unsigned char ch, uint32_t color)
{
    const uint8_t *glyph = s_font[ch & 0x7F];
    for (uint32_t row = 0; row < FONT_H; row++) {
        uint32_t y = py + row;
        if (y >= fb_h) break;
        uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < FONT_W; col++) {
            uint32_t x = px + col;
            if (x >= fb_w) break;
            if (bits & (1u << col))
                fb[y * pitch_px + x] = color;
        }
    }
}

/* Draw a null-terminated string starting at (px, py). */
static void blit_string(volatile uint32_t *fb, uint32_t pitch_px,
                        uint32_t fb_w, uint32_t fb_h,
                        uint32_t px, uint32_t py,
                        const char *str, uint32_t color)
{
    uint32_t cx = px;
    while (*str) {
        if (cx + FONT_W > fb_w) break;
        blit_char(fb, pitch_px, fb_w, fb_h, cx, py, (unsigned char)*str, color);
        cx += FONT_W + 1;
        str++;
    }
}

/* ---- Restart policy -----------------------------------------------------
 *
 * boot.conf `restart_on_halt=N` controls behavior:
 *   0 = permanent halt (default) -- wait for manual power cycle
 *   1 = auto-restart after 10s   -- suitable for unattended / kiosk
 *
 * Phase 0 failures always halt permanently (no config parsed yet).
 * Phase 1-2 BOOT_FATAL: respect boot.conf restart policy.
 * Phase 3 failures: log + serial console fallback (no halt).
 * panic_screen(): uses Registry AutoRestart key (separate from boot.conf).
 * -------------------------------------------------------------------- */

void boot_halt(const char *reason)
{
    /* Mark failure on the I/O-port 0x80 POST card + on-screen POST display
     * first. boot_post_write16 is volatile (no NVRAM write -- see boot_init.c);
     * next-boot failure detection instead relies on NVRAM still holding the
     * last milestone (!= POST16_BOOT_OK), since boot_halt runs before the
     * Phase 3 "succeeded" mark. */
    boot_post_write16(POST16_BOOT_FAILED);

    /* Arm abort-safe serial: boot_halt is terminal (it never returns), and it
     * is reached from failure paths that may already hold g_serial_lock or run
     * with a UART that never came up. From here serial_write is the bounded
     * try-lock path, which also covers kernel_subsystem_dump's output below. */
    serial_enter_emergency();

    /* Always write to serial first -- works regardless of framebuffer state */
    serial_write("\n[BOOT HALT] ");
    serial_write(reason ? reason : "(unknown reason)");
    serial_write("\n");

    /* Dump subsystem readiness so the serial log captures full state */
    kernel_subsystem_dump();

    serial_write("System halted. Check serial log for details.\n");
    serial_write("Recovery: https://impossible-os.dev/recovery\n");

    /* Framebuffer diagnostics -- only when fb is accessible AND the
     * pitch + dimensions are structurally sane.  A malformed boot_info
     * handoff must not write past the framebuffer.  The naive guard
     * `pitch >= width * 4u` u32-multiply-overflows when width >
     * UINT32_MAX/4 (~1G), wrapping small so a tiny pitch passes; the
     * form below snapshots the fields once, bounds dimensions to a
     * 16K x 16K sanity cap (4x the largest commercial display + 18
     * bits of headroom before any 32-bit pixel-count overflow), then
     * compares as pixels to stay overflow-safe. */
    uint32_t fb_pitch_bytes = g_boot_info.fb.pitch;
    uint32_t fb_w_snap      = g_boot_info.fb.width;
    uint32_t fb_h_snap      = g_boot_info.fb.height;
    /* Sanity cap before any arithmetic on the snapshots. */
    int fb_dims_ok = (fb_w_snap > 0 && fb_w_snap <= 16384u &&
                      fb_h_snap > 0 && fb_h_snap <= 16384u);
    /* Pitch must be 4-byte aligned; compare as pixels (overflow-
     * safe -- pitch_bytes / 4 cannot exceed UINT32_MAX/4 by
     * construction). */
    int fb_pitch_ok = ((fb_pitch_bytes % 4u) == 0 &&
                       (fb_pitch_bytes / 4u) >= fb_w_snap);
    if (g_boot_info.fb_available && g_boot_info.fb.addr &&
        fb_dims_ok && fb_pitch_ok) {

        volatile uint32_t *fb = (volatile uint32_t *)(uintptr_t)g_boot_info.fb.addr;
        uint32_t w       = fb_w_snap;
        uint32_t h       = fb_h_snap;
        uint32_t pitch   = fb_pitch_bytes / 4;  /* bytes → pixels (validated) */

        /* Red banner: top 40 rows */
        const uint32_t BANNER_H = 40;
        uint32_t banner_rows = (BANNER_H < h) ? BANNER_H : h;
        for (uint32_t row = 0; row < banner_rows; row++)
            for (uint32_t col = 0; col < w; col++)
                fb[row * pitch + col] = 0x00CC0000;  /* dark red */

        /* White "BOOT HALT" title in the banner */
        blit_string(fb, pitch, w, h, 8, 4,  "BOOT HALT", 0x00FFFFFF);
        blit_string(fb, pitch, w, h, 8, 14, "System halted.", 0x00FFFFFF);

        /* Reason string below the banner on black background */
        if (reason) {
            uint32_t text_y = BANNER_H + 8;
            blit_string(fb, pitch, w, h, 8, text_y, reason, 0x00FF4040);
            text_y += FONT_H + 4;
            blit_string(fb, pitch, w, h, 8, text_y,
                        "See serial output for details.", 0x00AAAAAA);
            text_y += FONT_H + 4;
            blit_string(fb, pitch, w, h, 8, text_y,
                        "https://impossible-os.dev/recovery", 0x004080FF);
        }
    }

    for (;;) __asm__ volatile ("hlt");
}
